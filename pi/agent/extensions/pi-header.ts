const PI_ART_NAMES = ["pi-logo", "reze", "power", "asuka-1", "asuka-2", "eva", "nerv"] as const;

if (PI_ART_NAMES.length !== PI_ARTS.length) {
  throw new Error("Each ASCII art must have a name");
}
if (new Set(PI_ART_NAMES).size !== PI_ART_NAMES.length) {
  throw new Error("ASCII art names must be unique");
}

const NAMED_PI_ARTS = PI_ARTS.map((lines, index) => {
  const name = PI_ART_NAMES[index];
  if (!name) throw new Error(`Missing name for ASCII art ${index + 1}`);
  return { name, lines };
});

type NamedPiArt = (typeof NAMED_PI_ARTS)[number];

function installHeader(ctx: ExtensionContext, selectedArt: NamedPiArt) {
  ctx.ui.setHeader((_tui, theme) => ({
    render(width: number): string[] {
      const art = selectedArt.lines.map((line) =>
        center(catppuccinFg(CATPPUCCIN.blue, line), width),
      );
      const version = center(theme.fg("muted", `Pi v${VERSION} · ${selectedArt.name}`), width);

      return [...art, version];
    },
    invalidate() {},
  }));
}

function center(line: string, width: number): string {
  const clipped = truncateToWidth(line, Math.max(0, width), "");
  const padding = Math.max(0, Math.floor((width - visibleWidth(clipped)) / 2));
  return " ".repeat(padding) + clipped;
}

export default function (pi: ExtensionAPI) {
  pi.registerFlag("ascii", {
    description: "Choose the header ASCII art by name",
    type: "string",
  });

  let selectedArt = NAMED_PI_ARTS[Math.floor(Math.random() * NAMED_PI_ARTS.length)]!;

  pi.on("session_start", async (_event, ctx) => {
    if (ctx.mode !== "tui") return;

    const asciiFlag = pi.getFlag("ascii");
    const flaggedArt =
      typeof asciiFlag === "string"
        ? NAMED_PI_ARTS.find((art) => art.name === asciiFlag)
        : undefined;

    if (typeof asciiFlag === "string" && !flaggedArt) {
      ctx.ui.notify(
        `Unknown ASCII art \"${asciiFlag}\". Available: ${NAMED_PI_ARTS.map((art) => art.name).join(", ")}`,
        "error",
      );
    }

    selectedArt = flaggedArt ?? NAMED_PI_ARTS[Math.floor(Math.random() * NAMED_PI_ARTS.length)]!;
    installHeader(ctx, selectedArt);
  });

  pi.registerCommand("ascii", {
    description: "Select the header ASCII art",
    handler: async (_args, ctx) => {
      if (ctx.mode !== "tui") {
        ctx.ui.notify("The ASCII art selector requires TUI mode", "error");
        return;
      }

      const selectedName = await ctx.ui.select(
        "Select ASCII art",
        NAMED_PI_ARTS.map((art) => art.name),
      );
      if (!selectedName) return;

      const nextArt = NAMED_PI_ARTS.find((art) => art.name === selectedName);
      if (!nextArt) return;

      selectedArt = nextArt;
      installHeader(ctx, selectedArt);
      ctx.ui.notify(`ASCII art changed to ${selectedArt.name}`, "info");
    },
  });
}
